// bundle-data.mjs -- pack everything "Teaching Lisp to Read" loads into one
// script, data/bundle.js, so that the page also works when its file is
// opened straight from disk.
//
//   node scripts/bundle-data.mjs
//
// A page opened from a file:// address may not fetch() other files, start a
// Web Worker, or read the pixels of an image file, but it may still run
// <script src> files and read images written as data: URLs. So when the page
// finds itself opened from a file, it loads this bundle instead of fetching:
// the text of lisp/digits.lisp, the sample digits (with the PNG as a data:
// URL), and the trained weights (base64). Served over http, as on GitHub
// Pages or with `pnpm dev`, the page fetches the files themselves and never
// loads the bundle.
//
// Run it again whenever lisp/digits.lisp, the sample or the weights change.
// `pnpm subset` and `pnpm train` run it for you.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path, encoding) => readFileSync(join(root, path), encoding);

const sample = JSON.parse(read("data/digits-sample.json", "utf8"));
const bundle = {
  digitsLisp: read("lisp/digits.lisp", "utf8"),
  sample: Object.assign(sample, {
    png: "data:image/png;base64," + read("data/digits-sample.png").toString("base64"),
  }),
  weights: read("data/digits.weights").toString("base64"),
};

const text =
  "// Generated by scripts/bundle-data.mjs from lisp/digits.lisp and data/. Do not edit.\n" +
  "// \"Teaching Lisp to Read\" loads this only when opened straight from disk.\n" +
  "window.TEACHING_LISP_BUNDLE = " + JSON.stringify(bundle) + ";\n";
writeFileSync(join(root, "data/bundle.js"), text);
console.log(`wrote data/bundle.js (${text.length} bytes)`);
